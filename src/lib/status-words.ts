function shuffle<T>(items: T[]): T[] {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// One shuffled deck for the whole page: a word comes back only after every other word has been shown.
let deck: string[] = [];
let last = '';

/** `n` words for one briefing, none repeated inside it or straight after the previous briefing. */
export function drawWords(n: number): string[] {
  const out: string[] = [];
  while (out.length < Math.min(n, STATUS_WORDS.length - 1)) {
    if (!deck.length) deck = shuffle(STATUS_WORDS.filter((w) => w !== last && !out.includes(w)));
    last = deck.pop()!;
    out.push(last);
  }
  return out;
}
